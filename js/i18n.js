export const SUPPORTED_LANGUAGES = ["en", "th"];

export function detectLanguage() {
  const browserLanguage = typeof navigator !== "undefined" ? navigator.language.toLowerCase() : "en";
  return browserLanguage.startsWith("th") ? "th" : "en";
}

export function translate(language, key, params = {}) {
  const locale = DICTIONARY[language] ?? DICTIONARY.en;
  const template = locale[key] ?? DICTIONARY.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? `{${token}}`));
}
